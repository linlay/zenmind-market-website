export type MarketLocale = keyof typeof marketCopy;

export function toI18nResource(value: any): any {
  if (typeof value === 'function') {
    const placeholders = Array.from({ length: value.length }, (_, index) => `{{arg${index}}}`);
    return value(...placeholders);
  }
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(
    Object.entries(value)
      .map(([key, entry]) => [key, toI18nResource(entry)])
      .filter(([, entry]) => entry !== undefined),
  );
}

export function getMarketCopy(
  locale: string,
  translate?: (key: string, fallback: string, values?: Record<string, unknown>) => string,
) {
  const copy: any = marketCopy[(locale === 'en-US' ? 'en-US' : 'zh-CN')];
  if (!translate) return copy;

  const wrap = (value: any, path: string): any => {
    if (!value || typeof value !== 'object' || typeof value === 'function') return value;
    return new Proxy(value, {
      get(target, property) {
        const entry = target[property];
        const key = path ? `${path}.${String(property)}` : String(property);
        if (typeof entry === 'string') return translate(key, entry);
        if (typeof entry === 'function') {
          return (...args: unknown[]) => translate(
            key,
            entry(...args),
            Object.fromEntries(args.map((argument, index) => [`arg${index}`, argument])),
          );
        }
        if (entry && typeof entry === 'object') return wrap(entry, key);
        return entry;
      },
    });
  };

  return wrap(copy, '');
}
